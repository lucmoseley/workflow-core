/*
 * read-edges-render.js — renders docs/test-read-edges.json's bytes from the
 * disk, the index or what a commit of named paths will carry. The generator
 * (generate-test-read-edges.js) writes and checks them; the test wrapper's
 * selection and manifest freshening read them. What an edge means:
 * lib/test-read-edges.js's header (#557, #998).
 */

const fs = require("node:fs");
const path = require("node:path");
const {
	buildManifest,
	gitList,
	gitOut,
	readWorkingTree,
} = require("./test-read-edges.js");
const { requiredGroup } = require("./regex-group.js");
const { readObjectBatch, listTree } = require("./git-objects.js");
const { GIT_TIMEOUT_MS, gitOutcome } = require("./git.js");
const { GIT_MODE } = require("./git-mode.js");

const OUT = "docs/test-read-edges.json";

const NOTE =
	"GENERATED by scripts/generate-test-read-edges.js — never hand-edited. " +
	"Maps a tracked file to the test files that read it at runtime rather than " +
	"importing it, which is the edge vitest --changed cannot see (mantahostels#2031).";

const INDEX_LINE = /^(\d+) ([0-9a-f]+) \d\t(.+)$/s;

/**
 * Whether the repo has a commit yet. A git failure throws rather than reading
 * as no HEAD, which would drop every tracked path from the index render.
 *
 * @param {string} root
 */
function hasHead(root) {
	const r = gitOutcome(["rev-parse", "--verify", "-q", "HEAD"], [1], root);
	if (!r.ok) throw new Error(`git rev-parse HEAD: ${r.why}`);
	return r.out.trim() !== "";
}

/**
 * Whether an index path is an intent-to-add entry (`git add -N`), which
 * `ls-files` lists but no commit carries (#3243). The staged diff omits a new
 * one and calls one over a HEAD path deleted.
 *
 * @param {string} root
 * @param {Map<string, string>} [head]  HEAD's blob ids, where already read
 * @returns {(file: string) => boolean}
 */
function readIsIntentToAdd(root, head) {
	const fields = gitList(root, [
		"diff",
		"--cached",
		"--name-status",
		"--no-renames",
		"-z",
	]);
	/** @type {Map<string, string>} */
	const staged = new Map();
	for (let i = 0; i + 1 < fields.length; i += 2) {
		const [status, file] = fields.slice(i, i + 2);
		if (status && file) staged.set(file, status);
	}
	const headIds = head ?? (hasHead(root) ? readHeadBlobIds(root) : new Map());
	return (file) =>
		staged.get(file) === "D" || (!staged.has(file) && !headIds.has(file));
}

/**
 * Blob ids by path, from `ls-files -s` (the index). A gitlink has no blob to
 * read, so it is left out, as is an intent-to-add entry.
 *
 * @param {string} root
 */
function readIndexBlobIds(root) {
	const isIntentToAdd = readIsIntentToAdd(root);
	/** @type {Map<string, string>} */
	const oidByPath = new Map();
	for (const entry of gitList(root, ["ls-files", "-s", "-z"])) {
		const m = INDEX_LINE.exec(entry);
		if (!m || m[1] === GIT_MODE.gitlink) continue;
		const file = requiredGroup(m, 3, INDEX_LINE);
		if (isIntentToAdd(file)) continue;
		if (!oidByPath.has(file))
			oidByPath.set(file, requiredGroup(m, 2, INDEX_LINE));
	}
	return oidByPath;
}

/**
 * Blob ids by path, from `ls-tree -r HEAD`, gitlinks left out as above.
 *
 * @param {string} root
 */
function readHeadBlobIds(root) {
	/** @type {Map<string, string>} */
	const oidByPath = new Map();
	for (const e of listTree("HEAD", [], { cwd: root, timeout: GIT_TIMEOUT_MS }))
		if (e.mode !== GIT_MODE.gitlink) oidByPath.set(e.path, e.sha);
	return oidByPath;
}

/**
 * A tree of blobs, overlaid by `disk` — paths read from the working tree
 * instead. Every tracked script is fetched in one `cat-file --batch` on first
 * read, tests and nearly every helper among them; any other helper, one blob
 * at a time.
 *
 * @param {string} root
 * @param {Map<string, string>} oidByPath
 * @param {Set<string>} [disk]
 */
function blobTree(root, oidByPath, disk = new Set()) {
	/** @type {Map<string, string> | undefined} */
	let blobs;
	const load = () => {
		const scripts = [...oidByPath].filter(([p]) =>
			/\.(?:tsx?|[mc]?js)$/.test(p),
		);
		const objects = readObjectBatch(
			scripts.map(([, o]) => o),
			"the tree's scripts",
			{
				cwd: root,
				timeout: GIT_TIMEOUT_MS,
				/* Every script blob at once: 17.3 MB on 23 Oct 2026, so 256 MiB
				 * keeps about fifteen times that. */
				maxBuffer: 1 << 28,
			},
		);
		/** @type {Map<string, string>} */
		const byPath = new Map();
		for (const [i, [p, o]] of scripts.entries()) {
			const object = objects[i];
			/* A blob read as empty drops its test's edges and passes the gate
			 * falsely, so an unreadable one refuses the render instead. */
			if (object?.type !== "blob")
				throw new Error(
					`git cat-file --batch: ${o} ${object?.type ?? "missing"}`,
				);
			byPath.set(p, object.body.toString("utf8"));
		}
		return byPath;
	};
	return {
		tracked: new Set([...oidByPath.keys(), ...disk]),
		read: (/** @type {string} */ p) => {
			if (disk.has(p)) return fs.readFileSync(path.join(root, p), "utf8");
			blobs ??= load();
			const text = blobs?.get(p);
			if (text !== undefined) return text;
			const o = oidByPath.get(p);
			if (!o) throw new Error(`${p}: not in the tree`);
			return gitOut(root, ["cat-file", "blob", o]).toString("utf8");
		},
	};
}

/**
 * The tree the index holds — on a pathspec commit, git's temporary index
 * (`GIT_INDEX_FILE`), which is HEAD plus the named paths: exactly what the
 * commit will carry, so neither a neighbour's deletion nor a neighbour's
 * unstaged edit on disk moves the verdict (#557).
 *
 * @param {string} root
 */
const readIndexTree = (root) => blobTree(root, readIndexBlobIds(root));

/**
 * What `git commit -- <only>` will carry, rendered before the commit: HEAD,
 * with each named path taken from disk or, where the disk has lost it, dropped.
 * A named intent-to-add entry over a HEAD path is dropped too, as the bare
 * commit whose refused `--check` named these paths deletes it (#3419). A
 * pathspec commit naming that path carries its disk bytes instead, so its own
 * `--check` refuses rather than passing falsely.
 *
 * @param {string} root
 * @param {string[]} only  file paths, as the commit names them
 */
function readCommitTree(root, only) {
	const head = readHeadBlobIds(root);
	const isIntentToAdd = readIsIntentToAdd(root, head);
	const indexed = new Set(gitList(root, ["ls-files", "-z"]));
	const isDroppedIntentToAdd = (/** @type {string} */ p) =>
		head.has(p) && indexed.has(p) && isIntentToAdd(p);
	const named = new Set(only);
	return blobTree(
		root,
		new Map([...head].filter(([p]) => !named.has(p))),
		new Set(
			only.filter(
				(p) => !isDroppedIntentToAdd(p) && fs.existsSync(path.join(root, p)),
			),
		),
	);
}

/**
 * The tree `render` reads: what a commit of `only` will carry, else the
 * index, else the disk.
 *
 * @param {string} root
 * @param {boolean} index
 * @param {string[] | undefined} only
 */
function readTreeFor(root, index, only) {
	if (only) return readCommitTree(root, only);
	if (index) return readIndexTree(root);
	return readWorkingTree(root);
}

/**
 * @param {string} root
 * @param {{ index?: boolean, only?: string[], sites?: boolean }} [opts]  read
 *   the index, or what a commit of `only` will carry, rather than the disk;
 *   `sites` also finds each test's unseen reads
 */
function render(root, { index = false, only, sites = false } = {}) {
	const tree = readTreeFor(root, index, only);
	const read = new Set();
	const { edges, anchored, tests, warnings, unseen } = buildManifest(
		tree.tracked,
		(p) => {
			read.add(p);
			return tree.read(p);
		},
		{ sites },
	);
	return {
		text: buildManifestText(edges),
		edges,
		anchored,
		tests,
		read,
		tree,
		warnings,
		unseen,
	};
}

/**
 * The manifest's bytes for `edges`, as every writer of it spells them.
 * @param {Record<string, string[]>} edges
 */
const buildManifestText = (edges) =>
	`${JSON.stringify({ $note: NOTE, edges }, null, "\t")}\n`;

module.exports = { OUT, buildManifestText, hasHead, render };
