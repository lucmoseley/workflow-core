/*
 * npm-run-hints-testkit.ts — the `npm run <name>` hints in a file's text that
 * an adopter cannot run (#1289, #1291), shared by the shipped-tree scan and
 * the unit cases that pin its reading (#1900).
 */

import { createRequire } from "node:module";

const require_ = createRequire(__filename);
const { citableLines } = require_("./qualify-citations.js");
const { requiredGroup }: typeof import("./regex-group.js") =
	require_("./regex-group.js");

const HINT = /npm run ([\w:-]*)/g;

/* Names an adopter running the matching module declares itself. */
const ADOPTER_DECLARES = new Set([
	/* The suites module's runners, which an adopter's suite runs through. */
	"test",
	"test:changed",
	"test:py",
	/* The suites module's read-graph manifest, regenerated by the same host. */
	"gen:test-read-edges",
	/* bisect-step.sh runs the host's own shellcheck gate. */
	"check:sh",
	/* adopter-skeleton.js names it only where the adopter declares it (#739). */
	"check:ci",
]);

/* A hint printed only where inCheckout() holds, only beside its node form,
 * naming a script read from the host's own package.json, or printed only to a
 * host that deploys to Vercel and so declares `build`. A name built at
 * runtime reads as its literal prefix: `gen:` for `gen:${name}`. */
const EXEMPT: Record<string, string[]> = {
	"docs/agents/rules/vercel-build-on-push.txt": ["build"],
	"scripts/check-doc-map.js": ["gen:"],
	"scripts/check-tracker-sweep.js": ["check:"],
	"scripts/generate-rule-fragments.js": ["gen:rule-fragments"],
	"scripts/lib/infer-commands.js": [""],
};

/** @returns each `rel:line: npm run <name>` in `text` an adopter cannot run */
export function hintsIn(rel: string, text: string): string[] {
	/*
	 * A script's comment lines, as the release build reads them; a fragment
	 * (`.txt`) is printed whole, so none of its lines is a comment.
	 */
	const comment = citableLines(rel);
	return text.split("\n").flatMap((line, i) =>
		comment?.(line)
			? []
			: [...line.matchAll(HINT)]
					.map((m) => requiredGroup(m, 1, HINT))
					.filter((name) => !ADOPTER_DECLARES.has(name))
					.filter((name) => !EXEMPT[rel]?.includes(name))
					.map((name) => `${rel}:${i + 1}: npm run ${name}`),
	);
}
